#!/usr/bin/env node
// ============================================================
// [AI BOTS - NEAR HACKATHON] Map data sync script.
//
// Bots move server-side, so the server needs the same map the clients
// use. The map lives in near-saboteur-frontend/src/game.jsx. Instead of
// copying it by hand (and letting the two drift apart), this script
// pulls the exact constant definitions out of game.jsx and writes them
// to bots/mapData.js.
//
// Re-run it whenever the map, rooms, gates, mission stations, spawn
// points or player collision numbers change in game.jsx:
//   node scripts/sync-map-from-frontend.js [path/to/game.jsx]
// (default path: ../near-saboteur-frontend/src/game.jsx)
// ============================================================
const fs = require("fs");
const path = require("path");

const gamePath = path.resolve(
  process.argv[2] || path.join(__dirname, "..", "..", "near-saboteur-frontend", "src", "game.jsx")
);
const outPath = path.join(__dirname, "..", "bots", "mapData.js");

// Order matters: later expressions may reference earlier names (e.g.
// TASK_RANGE = TILE * 1.6).
const NAMES = [
  "GRID_W", "GRID_H", "TILE", "VIEW_TILES", "VISION_RADIUS_TILES",
  "CAFETERIA_SPAWN_POINTS", "GRID", "ROOMS",
  "VENT_POSITIONS", "VENT_ADJACENCY", "VENT_INTERACT_RANGE_TILES",
  "DOORS", "TASK_POINTS", "GATES", "GATE_GROUP_A", "GATE_GROUP_B",
  "PLAYER_SIZE", "MOVE_SPEED", "SPEED_STEPS",
  "COLLISION_PAD_X", "COLLISION_PAD_TOP", "COLLISION_PAD_BOTTOM",
  "TASK_RANGE", "MISSION_DEFS", "MISSIONS_ASSIGNED_COUNT", "LINKED_MISSION_ROOMS",
  // Mission station trigger zones (nearbyTaskPoint in game.jsx)
  "ASSEMBLY_BTN", "ASSEMBLY_RANGE", "VERIFY_POD", "VERIFY_RANGE", "SECURITY_HUB", "SECURITY_RANGE",
  "VAULT_POD", "VAULT_RANGE", "STAKING_POD", "STAKING_RANGE", "CLAIM_POD", "CLAIM_RANGE",
  "ELEC_POD", "ELEC_RANGE", "NEARAI_POD", "NEARAI_RANGE", "NEARMERCH_POD", "NEARMERCH_RANGE",
  "IRONCLAW_POD", "IRONCLAW_RANGE", "LEGION_POD", "LEGION_RANGE", "EXCHANGE_POD", "EXCHANGE_RANGE",
  "MEME_POD", "MEME_RANGE", "CYBER_POD", "CYBER_RANGE",
  // Lobby room (percentage coordinates) - LOBBY_PLAYER_HALF_X's statement
  // also declares LOBBY_PLAYER_HALF_Y.
  "LOBBY_SOLIDS", "LOBBY_FLOOR", "LOBBY_PLAYER_HALF_X",
  // Vision + Security Hub camera feeds (what a bot could legitimately see)
  "VISION_RADIUS_SABOTAGED", "CAMERAS",
];

const src = fs.readFileSync(gamePath, "utf8");

// Returns the full `const NAME = ...;` statement for a top-level const,
// scanning past strings, template literals and comments so brackets or
// semicolons inside them don't end the statement early.
function extractConst(name) {
  const re = new RegExp(`^const ${name}\\s*=`, "m");
  const m = re.exec(src);
  if (!m) throw new Error(`Couldn't find "const ${name} =" in ${gamePath}`);
  let i = m.index + m[0].length;
  let depth = 0;
  while (i < src.length) {
    const ch = src[i];
    const next = src[i + 1];
    if (ch === "/" && next === "/") { i = src.indexOf("\n", i); if (i < 0) break; continue; }
    if (ch === "/" && next === "*") { i = src.indexOf("*/", i) + 2; continue; }
    if (ch === "'" || ch === '"' || ch === "`") {
      i++;
      while (i < src.length && src[i] !== ch) { if (src[i] === "\\") i++; i++; }
      i++;
      continue;
    }
    if (ch === "[" || ch === "{" || ch === "(") depth++;
    else if (ch === "]" || ch === "}" || ch === ")") depth--;
    else if (ch === ";" && depth === 0) return src.slice(m.index, i + 1);
    else if (ch === "\n" && depth === 0) {
      // Statement without a trailing semicolon - stop at end of line.
      return src.slice(m.index, i).replace(/\s+$/, "") + ";";
    }
    i++;
  }
  throw new Error(`Couldn't find the end of "const ${name}"`);
}

// Strip trailing // comments from each line (outside strings) to keep the
// generated file compact. Long GRID string has no comments.
function stripLineComments(code) {
  return code.split("\n").map((line) => {
    let inStr = null;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (inStr) { if (c === "\\") i++; else if (c === inStr) inStr = null; continue; }
      if (c === "'" || c === '"' || c === "`") inStr = c;
      else if (c === "/" && line[i + 1] === "/") return line.slice(0, i).replace(/\s+$/, "");
    }
    return line;
  }).filter((l) => l.trim() !== "").join("\n");
}

const body = NAMES.map((n) => stripLineComments(extractConst(n))).join("\n\n");

const out = `// ============================================================
// AUTO-GENERATED by scripts/sync-map-from-frontend.js - DO NOT EDIT BY HAND.
// Source: near-saboteur-frontend/src/game.jsx
// Generated: ${new Date().toISOString()}
// Re-run the script after changing the map in game.jsx.
// ============================================================
/* eslint-disable */

${body}

module.exports = {
  ${NAMES.join(",\n  ")},
  LOBBY_PLAYER_HALF_Y,
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);

// Sanity check: load it back and verify the grid size matches.
delete require.cache[require.resolve(outPath)];
const data = require(outPath);
if (data.GRID.length !== data.GRID_W * data.GRID_H) {
  throw new Error(`GRID length ${data.GRID.length} != GRID_W*GRID_H ${data.GRID_W * data.GRID_H}`);
}
console.log(`Wrote ${path.relative(process.cwd(), outPath)} (${NAMES.length} constants, grid ${data.GRID_W}x${data.GRID_H}, ${data.ROOMS.length} rooms, ${data.TASK_POINTS.length} mission stations).`);
